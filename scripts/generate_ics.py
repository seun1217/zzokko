def esc(text: str) -> str:
    """RFC 5545 TEXT 이스케이프."""
    return (text.replace("\\", "\\\\")
                .replace(";", "\\;")
                .replace(",", "\\,")
                .replace("\n", "\\n"))


def fold(line: str) -> str:
    """75옥텟 제한에 맞춰 줄 접기 (UTF-8 문자 경계 유지)."""
    out, cur, cur_len = [], "", 0
    limit = 73  # 이어지는 줄은 앞에 공백 1옥텟이 붙으므로 여유 있게
    for ch in line:
        ch_len = len(ch.encode("utf-8"))
        if cur_len + ch_len > limit:
            out.append(cur)
            cur, cur_len = " " + ch, 1 + ch_len
        else:
            cur += ch
            cur_len += ch_len
    out.append(cur)
    return "\r\n".join(out)


